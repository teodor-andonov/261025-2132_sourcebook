import test from 'node:test';
import assert from 'node:assert/strict';
import {parseFilename,appendToken,ownedToken,validName} from '../src/identity.mjs';
test('appends suffix before extension',()=>assert.equal(appendToken('Facade.pdf','ab',967),'Facade[ab967].pdf'));
test('two catalogs share file',()=>assert.equal(appendToken('Facade[ab967].pdf','c',5),'Facade[ab967][c5].pdf'));
test('read both identities',()=>assert.deepEqual(parseFilename('Facade[ab967][c5].pdf').tokens.map(t=>[t.code,t.number]),[['ab',967],['c',5]]));
test('friendly filename',()=>assert.equal(parseFilename('Facade[ab967][c5].pdf').displayName,'Facade.pdf'));
test('no duplicate token',()=>assert.throws(()=>appendToken('a[ab1].png','ab',2)));
test('non-ID brackets survive',()=>assert.equal(parseFilename('material[revision].png').displayName,'material[revision].png'));
test('dot file remains valid',()=>assert.equal(appendToken('.gitignore','ab',1),'.gitignore[ab1]'));
test('catalog name validation',()=>{assert.equal(validName('Research'),true);assert.equal(validName('X/Y'),false);});
